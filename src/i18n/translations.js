/**
 * Returns translation text by key and language code.
 * Falls back to English or Russian if key is missing.
 * @param {string} key
 * @param {string} lang
 * @returns {string}
 */
export function t(key, lang = 'ru') {
  const dict = translations[lang] || translations.en || translations.ru;
  if (dict[key]) return dict[key];
  if (translations.ru[key]) return translations.ru[key];
  if (translations.en[key]) return translations.en[key];
  return key;
}
